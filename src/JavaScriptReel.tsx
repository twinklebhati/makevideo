// Subtitles for the voiceover. Keep the text in sync with scripts/generate-voice.mjs;
// `durationInFrames` is each clip's length (printed by `npm run voice`).
const captionTracks = [
  {
    from: 0,
    durationInFrames: 168,
    phrases: [
      "Here's a classic JavaScript interview question.",
      "What does this code print?",
      "Drop your answer in the comments!",
    ],
  },
  {
    from: 450,
    durationInFrames: 674,
    phrases: [
      "The answer is: 1, 4, 3, 2.",
      "1 and 4 print first,",
      "because they're synchronous and run straight on the call stack.",
      "3 is next, because promise callbacks go into the microtask queue,",
      "which empties right after the current script.",
      "And 2 comes last.",
      "setTimeout is a macrotask, so even with zero delay,",
      "it waits for the next turn of the event loop.",
    ],
  },
];

// Split each track's duration across its phrases in proportion to their length
const captions = captionTracks.flatMap(({ from, durationInFrames, phrases }) => {
  const totalChars = phrases.reduce((sum, p) => sum + p.length, 0);
  let start = from;
  return phrases.map((text) => {
    const end = start + (text.length / totalChars) * durationInFrames;
    const caption = { text, start: Math.round(start), end: Math.round(end) };
    start = end;
    return caption;
  });
});

